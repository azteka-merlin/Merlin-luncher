    function formatBytes(bytes) {
        if (!Number.isFinite(bytes) || bytes <= 0) return '—';
        const units = ['B', 'KB', 'MB', 'GB'];
        let value = bytes;
        let index = 0;
        while (value >= 1024 && index < units.length - 1) {
            value /= 1024;
            index += 1;
        }
        const rounded = value >= 10 || index === 0 ? Math.round(value) : value.toFixed(1);
        return `${rounded} ${units[index]}`;
    }

    function formatDuration(seconds) {
        if (!Number.isFinite(seconds) || seconds === null) return '—';
        const totalSeconds = Math.max(0, Math.round(seconds));
        const hours = Math.floor(totalSeconds / 3600);
        const minutes = Math.floor((totalSeconds % 3600) / 60);
        const secs = totalSeconds % 60;
        if (hours > 0) return `${hours}h ${String(minutes).padStart(2, '0')}m`;
        if (minutes > 0) return `${minutes}m ${String(secs).padStart(2, '0')}s`;
        return `${secs}s`;
    }

    function countdownValue(expiresAt) {
        if (!expiresAt) return null;
        const expiry = new Date(expiresAt);
        if (Number.isNaN(expiry.getTime())) return null;
        const remainingMs = expiry.getTime() - Date.now();
        if (remainingMs <= 0) return null;

        const totalMinutes = Math.ceil(remainingMs / 60000);
        const days = Math.floor(totalMinutes / (24 * 60));
        const hours = Math.floor((totalMinutes % (24 * 60)) / 60);
        const minutes = totalMinutes % 60;
        const parts = [];

        if (days > 0) parts.push(tr('premium_duration_day', { count: days }));
        if (hours > 0 || days > 0) {
            parts.push(tr('premium_duration_hour', {
                count: String(hours).padStart(days > 0 ? 2 : 1, '0')
            }));
        }
        parts.push(tr('premium_duration_minute', {
            count: String(minutes).padStart(days > 0 || hours > 0 ? 2 : 1, '0')
        }));
        return parts.join(' ');
    }

